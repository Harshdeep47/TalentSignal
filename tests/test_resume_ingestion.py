def test_sniff_kind_uses_magic_bytes():
    assert sniff_kind(b"%PDF-1.7", "x.docx") == "pdf"
    assert sniff_kind(b"PK\x03\x04", "cv.docx") == "docx"
    assert sniff_kind(b"PK\x03\x04", "all.zip") == "zip"
    assert sniff_kind(b"PK\x03\x04", "cv.xlsx") == "zip-unknown"
    assert sniff_kind(b"\xd0\xcf\x11\xe0", "old.doc") is None
    assert sniff_kind(b"hello", "cv.pdf") is None



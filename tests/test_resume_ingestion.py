def test_record_is_valid_and_contains_no_contact_details(asha):
    _, ex = asha
    rec = to_candidate_record(ex, "RES_abc123_def45678", "asha_verma")
    out, issues = Normalizer().normalize(rec)
    assert out is not None and not [i for i in issues if i.level == "error"]
    blob = json.dumps(out)
    for secret in ("asha.verma@example.com", "98765", "linkedin.com"):
        assert secret not in blob
    p = out["profile"]
    assert p["anonymized_name"] == "Asha Verma" and p["current_title"] == "Senior Machine Learning Engineer"
    assert p["years_of_experience"] == 7.0 and p["current_company_size"] is None
    assert out["career_history"][0]["is_current"] is True
    assert all(s["duration_months"] is None and s["endorsements"] is None for s in out["skills"])
    sig = out["redrob_signals"]
    assert all(v is None for v in sig.values() if not isinstance(v, dict))
    assert sig["skill_assessment_scores"] == {}
    assert sig["expected_salary_range_inr_lpa"] == {"min": None, "max": None}
    assert "Projects:" in p["summary"] and "Achievements:" in p["summary"]


def test_resume_candidates_rank_with_the_existing_engine(tmp_path, asha, rohan, redrob_spec):
    recs = standard_pool(n_filler=20)
    recs.append(to_candidate_record(asha[1], "RES_aaaaaa_00000001", "a"))
    recs.append(to_candidate_record(rohan[1], "RES_aaaaaa_00000002", "r"))
    src = write_jsonl(recs, tmp_path / "pool.jsonl")
    build_index(src, tmp_path / "ix", embed=False)
    pool = score_pool(DatasetIndex(tmp_path / "ix"), redrob_spec, embedder=None)
    t = pool.table.set_index("candidate_id")
    assert {"RES_aaaaaa_00000001", "RES_aaaaaa_00000002"} <= set(t.index)
    # The ML engineer resume should outrank the backend developer resume for an ML role.
    assert t.loc["RES_aaaaaa_00000001", "rank"] < t.loc["RES_aaaaaa_00000002", "rank"]
    assert 0 <= float(t.loc["RES_aaaaaa_00000001", "overall"]) <= 1


# ---- ZIP safety -----------------------------------------------------------------
def _zip(entries: dict[str, bytes], encrypt_flag: str | None = None, compress=zipfile.ZIP_DEFLATED) -> zipfile.ZipFile:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compress) as z:
        for n, data in entries.items():
            z.writestr(n, data)
    if encrypt_flag:
        raw = bytearray(buf.getvalue())
        zf = zipfile.ZipFile(io.BytesIO(bytes(raw)))
        info = zf.getinfo(encrypt_flag)
        # set the "encrypted" general-purpose bit in the local and central headers
        raw[info.header_offset + 6] |= 0x1
        idx = raw.find(b"PK\x01\x02")
        while idx != -1:
            name_len = int.from_bytes(raw[idx + 28:idx + 30], "little")
            if raw[idx + 46:idx + 46 + name_len].decode() == encrypt_flag:
                raw[idx + 8] |= 0x1
            idx = raw.find(b"PK\x01\x02", idx + 4)
        buf = io.BytesIO(bytes(raw))
    return zipfile.ZipFile(buf)


def test_zip_member_classification():
    pdf = (FIX / "asha_verma.pdf").read_bytes()
    zf = _zip({"../../evil/cv.pdf": pdf, "inner.zip": b"PK", "notes.txt": b"x", "__MACOSX/._cv.pdf": b"x",
               ".DS_Store": b"x", "folder/ok.docx": b"PK", "secret.pdf": pdf}, encrypt_flag="secret.pdf")
    members = {m.display_name: m.problem_code for m in zipsafe.iter_members(zf)}
    assert members == {"cv.pdf": None, "inner.zip": "nested_archive", "notes.txt": "unsupported_format",
                       "ok.docx": None, "secret.pdf": "encrypted"}


def test_zip_bomb_ratio_and_member_limits(monkeypatch):
    zf = _zip({"bomb.pdf": b"\0" * (5 * 1024 * 1024)})
    assert next(zipsafe.iter_members(zf)).problem_code == "suspicious_archive_entry"
    monkeypatch.setattr(zipsafe, "MAX_MEMBERS", 2)
    with pytest.raises(zipsafe.ZipArchiveError):
        list(zipsafe.iter_members(_zip({"a.pdf": b"1", "b.pdf": b"2", "c.pdf": b"3"})))


def test_copy_member_enforces_limit_while_streaming():
    zf = _zip({"a.pdf": b"x" * 5000}, compress=zipfile.ZIP_STORED)
    out = io.BytesIO()
    with pytest.raises(zipsafe.ZipArchiveError):
        zipsafe.copy_member(zf, zf.getinfo("a.pdf"), out, limit=1000)
    assert zipsafe.copy_member(zf, zf.getinfo("a.pdf"), io.BytesIO(), limit=10_000) == 5000
